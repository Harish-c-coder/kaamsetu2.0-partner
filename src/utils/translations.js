export function translatePhrase(text, lang) {
  if (!text || typeof text !== 'string') return text;
  if (lang === 'en') return text;
  const match = DICTIONARY[text];
  if (match && match[lang]) return match[lang];
  const trimmed = text.trim();
  const matchTrimmed = DICTIONARY[trimmed];
  if (matchTrimmed && matchTrimmed[lang]) return matchTrimmed[lang];
  return text;
}

